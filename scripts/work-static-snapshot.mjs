#!/usr/bin/env node
// Extracts the hand-authored /work exhibit titles and facet labels from
// src/app/work/page.tsx into src/lib/work/static-titles.json, the snapshot
// the submission lint and the panel's editorial critic check uniqueness
// against (§5.16). A snapshot that silently drifts is worse than none, so:
//
//   node scripts/work-static-snapshot.mjs --check   # diff, exit 1 on drift
//   node scripts/work-static-snapshot.mjs --write   # regenerate the JSON
//
// --check runs inside scripts/check-build-warnings.sh (npm run build:check),
// so editing a static card without regenerating the snapshot fails the gate.

import fs from "node:fs";
import path from "node:path";
import url from "node:url";

const root = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const pagePath = path.join(root, "src/app/work/page.tsx");
const jsonPath = path.join(root, "src/lib/work/static-titles.json");

const src = fs.readFileSync(pagePath, "utf8");

function decode(s) {
  return s
    .replace(/&apos;/g, "'")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/\{\s*"([^"]*)"\s*\}/g, "$1")
    .replace(/\s+/g, " ")
    .trim();
}

// Exhibit titles: the <h2 className="mt-6">...</h2> inside each id'd section.
const titles = [...src.matchAll(/<h2 className="mt-6">([\s\S]*?)<\/h2>/g)].map(
  (m) => decode(m[1].replace(/<[^>]+>/g, ""))
);

// Facet labels: mono h3s; the label is the text after the numbered span.
const facetLabels = [
  ...src.matchAll(
    /<h3 className="mono text-xs uppercase tracking-\[0\.2em\] text-light">\s*<span className="text-faint">[^<]*<\/span>([\s\S]*?)<\/h3>/g
  ),
].map((m) => decode(m[1].replace(/<[^>]+>/g, "")));

// Anchor ids: guard the slug namespace (community slugs are team-*).
const anchorIds = [...src.matchAll(/<section id="([^"]+)"/g)].map((m) => m[1]);

const snapshot = {
  note:
    "GENERATED by scripts/work-static-snapshot.mjs from src/app/work/page.tsx. Do not hand-edit; run with --write after changing static /work cards.",
  titles,
  facetLabels: [...new Set(facetLabels)],
  anchorIds,
};

const rendered = JSON.stringify(snapshot, null, 2) + "\n";
const mode = process.argv[2];

if (mode === "--write") {
  fs.writeFileSync(jsonPath, rendered);
  console.log(
    `work-static-snapshot: wrote ${titles.length} titles, ${snapshot.facetLabels.length} facet labels, ${anchorIds.length} anchors.`
  );
} else {
  let existing = "";
  try {
    existing = fs.readFileSync(jsonPath, "utf8");
  } catch {
    // missing counts as drift
  }
  if (existing !== rendered) {
    console.error(
      "work-static-snapshot: DRIFT - src/lib/work/static-titles.json no longer matches src/app/work/page.tsx."
    );
    console.error("Run: node scripts/work-static-snapshot.mjs --write");
    process.exit(1);
  }
  console.log("work-static-snapshot: OK - snapshot matches page.tsx.");
}
